#!/usr/bin/env python3
"""Make the RFSAT boot logo for the rover's OLED (Firmware/RTK_Everywhere/icons_rfsat.h).

  python3 rfsat_logo.py                    # text logo: "RFSAT" over "LIMITED"
  python3 rfsat_logo.py logo.png           # from an image (any size; scaled to fit 128 x 48, dark on light or
                                           # light on dark is detected; use --invert if it comes out reversed)

The display draws white pixels on black. The array is in the display's page format: one byte per column for
each band of 8 rows, least significant bit at the top (the same format as the other logos in icons.h).
Needs Pillow (pip install pillow).
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont, ImageOps

W, H = 128, 48
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "RTK_Everywhere", "icons_rfsat.h")
FONTS = ["/usr/share/fonts/truetype/google-fonts/Poppins-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
         "C:/Windows/Fonts/arialbd.ttf", "/Library/Fonts/Arial Bold.ttf"]


def font(size):
    for f in FONTS:
        if os.path.exists(f):
            return ImageFont.truetype(f, size)
    return ImageFont.load_default()


def text_logo():
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im)
    big, small = font(34), font(11)
    t = "RFSAT"
    bb = d.textbbox((0, 0), t, font=big)
    d.text(((W - (bb[2] - bb[0])) // 2 - bb[0], 2 - bb[1]), t, font=big, fill=1)
    y = 2 + (bb[3] - bb[1]) + 4
    d.line([(14, y), (W - 15, y)], fill=1)
    s = "L I M I T E D"
    sb = d.textbbox((0, 0), s, font=small)
    d.text(((W - (sb[2] - sb[0])) // 2 - sb[0], y + 4 - sb[1]), s, font=small, fill=1)
    return im


def image_logo(path, invert):
    src = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", src.size, (255, 255, 255, 255))
    g = Image.alpha_composite(bg, src).convert("L")
    # dark artwork on a light background becomes white pixels on the black display
    if sum(g.getdata()) / (g.width * g.height) > 127:
        g = ImageOps.invert(g)
    if invert:
        g = ImageOps.invert(g)
    g.thumbnail((W, H), Image.LANCZOS)
    im = Image.new("L", (W, H), 0)
    im.paste(g, ((W - g.width) // 2, (H - g.height) // 2))
    return im.point(lambda v: 1 if v > 110 else 0, "1")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    im = image_logo(args[0], "--invert" in sys.argv) if args else text_logo()
    px = im.load()
    data = []
    for page in range(H // 8):
        for x in range(W):
            b = 0
            for bit in range(8):
                if px[x, page * 8 + bit]:
                    b |= 1 << bit
            data.append(b)
    rows = [", ".join(f"0x{v:02X}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    with open(OUT, "w", newline="\n") as f:
        f.write("// RFSAT Limited boot logo, " + f"{W} x {H}" + ". Generated by Firmware/Tools/rfsat_logo.py: edit that, not this file.\n")
        f.write("#pragma once\n\n")
        f.write(f"const uint8_t logoRFSAT_Height = {H};\nconst uint8_t logoRFSAT_Width = {W};\nconst uint8_t logoRFSAT[] = {{\n    ")
        f.write(",\n    ".join(rows) + "\n};\n")
    for y in range(H):  # preview
        print("".join("#" if px[x, y] else "." for x in range(W)))
    print("written", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
